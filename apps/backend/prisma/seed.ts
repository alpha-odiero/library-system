/**
 * Seed orchestrator.
 *
 * Safe to re-run: every stage upserts on a natural key, so `npm run db:seed`
 * converges rather than duplicating.
 *
 * Two tiers, deliberately separated:
 *   • config (roles, permissions, member types, settings) — always seeded;
 *   • demo (Central Library, branches, sample catalogue, `*@library.test`
 *     logins) — seeded ONLY with `--demo` or `SEED_DEMO_DATA=true`, so a plain
 *     `npm run db:seed` can never repopulate a database with sample data.
 *
 * Deliberate omissions (they arrive with the module that owns them):
 *   â€¢ active loans, returns, renewals  â€” Phase D, generated by a scenario
 *                                         runner so the concurrency tests have
 *                                         deterministic fixtures
 *   â€¢ fines and payments               â€” Phase D, for the same reason
 *   â€¢ reservations                     â€” Phase D
 *
 * Seeding circulation state here would hand the Phase D tests a moving target,
 * and a seeded "already overdue" loan quietly changes what a dashboard means.
 */

import { randomBytes } from 'node:crypto';
import { hash } from 'argon2';
import type { CopyCondition, PrismaClient } from '@prisma/client';
import { prisma } from '../src/config/database.js';
import { argon2Options, env } from '../src/config/env.js';
import { logger } from '../src/config/logger.js';
import { seedPermissionsAndRoles } from './seed/permissions.js';
import { MEMBER_TYPE_SEEDS, SETTING_SEEDS } from './seed/member-types.js';
import { SEED_PASSWORD, SEED_USERS } from './seed/users.js';
import {
  AUTHORS,
  BOOKS,
  BRANCHES,
  CATEGORIES,
  COPY_ALLOCATION,
  LOCATIONS,
  PUBLISHERS,
} from './seed/catalog.js';

/** Refuses to plant development credentials into a production database. */
function assertNotProduction(): void {
  if (env.NODE_ENV === 'production') {
    throw new Error(
      'Refusing to seed a production database. Development accounts must never exist in production.',
    );
  }
}

/**
 * Demo content (the Central Library tenant, its branches/catalogue and the
 * `*@library.test` accounts) is NEVER planted implicitly. Config data — roles,
 * permissions, member types and settings — is safe reference data and always
 * seeds; the sample catalogue and development logins require an explicit
 * `--demo` flag or `SEED_DEMO_DATA=true`. This is what makes it impossible for
 * `npm run db:seed` alone to repopulate a database with demo data.
 */
function wantsDemoData(): boolean {
  return process.argv.includes('--demo') || process.env.SEED_DEMO_DATA === 'true';
}

/* â”€â”€ Barcode / QR generation â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€ */

/**
 * Code 128-compatible payload. Checked in the service layer during Phase E
 * (scan lookup), generated here so seeded data is indistinguishable from
 * data created through the API.
 */
function makeBarcode(): string {
  return `BC${randomBytes(6).toString('hex').toUpperCase()}`;
}

/** Opaque 32-char token. Deliberately NOT derived from the accession number. */
function makeQrToken(): string {
  return randomBytes(16).toString('hex');
}

function makeAccessionNumber(branchCode: string, isbn13: string, sequence: number): string {
  return `${branchCode}/${new Date().getFullYear()}/${isbn13}/${String(sequence + 1).padStart(3, '0')}`;
}

/* â”€â”€ Stages â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€ */

async function seedLibrary(db: PrismaClient): Promise<{ id: string }> {
  const library = await db.library.upsert({
    where: { code: 'CENTRAL' },
    update: {},
    create: {
      code: 'CENTRAL',
      name: 'Central Library',
      legalName: 'Central Library Board',
      email: 'library@centrallibrary.org',
      phone: '+254 20 222 4000',
      address: 'Library Road, Nairobi',
      timezone: env.TIMEZONE,
    },
  });

  await db.library.update({ where: { id: library.id }, data: { timezone: env.TIMEZONE } });

  logger.info({ library: library.code }, 'Library seeded');
  return library;
}

async function seedBranches(db: PrismaClient, libraryId: string): Promise<Map<string, string>> {
  const byCode = new Map<string, string>();

  for (const branch of BRANCHES) {
    const record = await db.branch.upsert({
      where: { code: branch.code },
      update: {
        name: branch.name,
        email: branch.email,
        phone: branch.phone,
        address: branch.address,
        isActive: branch.isActive ?? true,
      },
      create: {
        libraryId,
        code: branch.code,
        name: branch.name,
        email: branch.email,
        phone: branch.phone,
        address: branch.address,
        openedAt: new Date('2015-01-01T00:00:00Z'),
        isActive: branch.isActive ?? true,
      },
    });
    byCode.set(branch.code, record.id);
  }

  logger.info({ branches: byCode.size }, 'Branches seeded');
  return byCode;
}

async function seedLocations(
  db: PrismaClient,
  branchIds: Map<string, string>,
): Promise<{ shelves: Map<string, string>; locations: Map<string, string> }> {
  const shelves = new Map<string, string>();
  const locations = new Map<string, string>();

  for (const location of LOCATIONS) {
    const branchId = branchIds.get(location.branchCode);
    if (!branchId) continue;

    const record = await db.location.upsert({
      where: { branchId_code: { branchId, code: location.code } },
      update: { name: location.name, floor: location.floor },
      create: { branchId, code: location.code, name: location.name, floor: location.floor },
    });
    locations.set(`${location.branchCode}/${location.code}`, record.id);

    for (const shelf of location.shelves) {
      const shelfRecord = await db.shelf.upsert({
        where: { locationId_code: { locationId: record.id, code: shelf.code } },
        update: { capacity: shelf.capacity },
        create: { locationId: record.id, code: shelf.code, capacity: shelf.capacity },
      });
      shelves.set(`${location.branchCode}/${shelf.code}`, shelfRecord.id);
    }
  }

  logger.info({ locations: locations.size, shelves: shelves.size }, 'Locations and shelves seeded');
  return { shelves, locations };
}

async function seedMemberTypes(db: PrismaClient): Promise<Map<string, string>> {
  const byCode = new Map<string, string>();

  for (const type of MEMBER_TYPE_SEEDS) {
    const record = await db.memberType.upsert({
      where: { code: type.code },
      // Never overwrite an administrator's tuned policy: only create a missing
      // type. Re-running the seed must be safe for a live library.
      update: {},
      create: {
        code: type.code,
        name: type.name,
        maxActiveLoans: type.maxActiveLoans,
        loanDurationDays: type.loanDurationDays,
        maxRenewals: type.maxRenewals,
        renewalDurationDays: type.renewalDurationDays,
        gracePeriodDays: type.gracePeriodDays,
        finePerDay: type.finePerDay,
        maxFineCap: type.maxFineCap,
        reservationLimit: type.reservationLimit,
        holdDurationDays: type.holdDurationDays,
        requiresApproval: type.requiresApproval,
      },
    });
    byCode.set(type.code, record.id);
  }

  logger.info({ memberTypes: byCode.size }, 'Member types seeded');
  return byCode;
}

async function seedSettings(db: PrismaClient): Promise<void> {
  for (const setting of SETTING_SEEDS) {
    const valueType = setting.valueType;

    await db.setting.upsert({
      where: { key: setting.key },
      // Metadata may be refreshed, but NEVER the operator-chosen `value`:
      // a re-run must not overwrite a live library's configuration.
      update: {
        valueType,
        description: setting.description,
        category: setting.category,
        isPublic: setting.isPublic ?? false,
      },
      create: {
        key: setting.key,
        value: setting.value as never,
        valueType,
        category: setting.category,
        description: setting.description,
        isPublic: setting.isPublic ?? false,
      },
    });
  }

  logger.info({ settings: SETTING_SEEDS.length }, 'Settings seeded');
}

async function seedUsers(
  db: PrismaClient,
  branchIds: Map<string, string>,
  memberTypeIds: Map<string, string>,
): Promise<void> {
  // One hash reused across seed accounts: argon2id is deliberately slow, and
  // hashing the same throwaway password six times adds nothing.
  // `hash()` takes the algorithm via `argon2Options.type`, not as a function.
  const passwordHash = await hash(SEED_PASSWORD, argon2Options);
  const now = new Date();

  for (const seed of SEED_USERS) {
    const role = await db.role.findUniqueOrThrow({ where: { code: seed.roleCode } });
    const primaryBranchId = branchIds.get(seed.branchCodes[0] ?? '') ?? null;

    const user = await db.user.upsert({
      where: { email: seed.email },
      update: {
        firstName: seed.firstName,
        lastName: seed.lastName,
        phone: seed.phone,
        roleId: role.id,
        passwordHash,
        emailVerifiedAt: seed.verified ? now : null,
        status: 'ACTIVE',
        deletedAt: null,
      },
      create: {
        email: seed.email,
        phone: seed.phone,
        passwordHash,
        firstName: seed.firstName,
        lastName: seed.lastName,
        roleId: role.id,
        primaryBranchId,
        emailVerifiedAt: seed.verified ? now : null,
      },
    });

    await db.userBranch.deleteMany({ where: { userId: user.id } });
    await db.userBranch.createMany({
      data: seed.branchCodes
        .map((code) => branchIds.get(code))
        .filter((id): id is string => Boolean(id))
        .map((branchId) => ({ userId: user.id, branchId })),
      skipDuplicates: true,
    });

    if (seed.member) {
      const memberTypeId = memberTypeIds.get(seed.member.memberTypeCode);
      const homeBranchId = branchIds.get(seed.member.branchCode);

      if (memberTypeId && homeBranchId) {
        const joinedAt = new Date(now.getTime() + seed.member.joinedAtOffsetDays * 86_400_000);
        const validityDays = 365;
        const expiresAt = new Date(joinedAt.getTime() + validityDays * 86_400_000);

        await db.member.upsert({
          where: { userId: user.id },
          update: {
            memberTypeId,
            homeBranchId,
            status: seed.member.status ?? 'ACTIVE',
            joinedAt,
            expiresAt,
          },
          create: {
            membershipNumber: seed.member.membershipNumber,
            userId: user.id,
            memberTypeId,
            homeBranchId,
            status: seed.member.status ?? 'ACTIVE',
            joinedAt,
            expiresAt,
          },
        });
      }
    }
  }

  logger.info({ users: SEED_USERS.length, password: '(development only)' }, 'Users seeded');
}

async function seedCatalog(
  db: PrismaClient,
  branchIds: Map<string, string>,
  shelfIds: Map<string, string>,
): Promise<void> {
  const authorIds = new Map<string, string>();

  for (const author of AUTHORS) {
    // Authors have no natural unique key other than the name, so this is
    // find-then-write rather than an upsert.
    const existing = await db.author.findFirst({
      where: { name: author.name },
      select: { id: true },
    });
    const record = existing
      ? await db.author.update({
          where: { id: existing.id },
          data: {
            name: author.name,
            sortName: author.sortName,
            nationality: author.nationality ?? null,
            birthYear: author.birthYear ?? null,
          },
        })
      : await db.author.create({
          data: {
            name: author.name,
            sortName: author.sortName,
            nationality: author.nationality,
            birthYear: author.birthYear,
          },
        });

    authorIds.set(author.name, record.id);
  }

  for (const publisher of PUBLISHERS) {
    await db.publisher.upsert({
      where: { name: publisher.name },
      update: { country: publisher.country, website: publisher.website },
      create: { name: publisher.name, country: publisher.country, website: publisher.website },
    });
  }

  const categoryIds = new Map<string, string>();
  // Parents first so a child can resolve its parentId.
  const ordered = [...CATEGORIES].sort((a, b) => (a.parentSlug ? 1 : 0) - (b.parentSlug ? 1 : 0));
  for (const category of ordered) {
    const existing = await db.category.findUnique({ where: { slug: category.slug } });
    const parentId = category.parentSlug ? categoryIds.get(category.parentSlug) : undefined;

    const record = existing
      ? await db.category.update({
          where: { id: existing.id },
          data: {
            name: category.name,
            description: category.description,
            parentId: parentId ?? null,
          },
        })
      : await db.category.create({
          data: {
            name: category.name,
            slug: category.slug,
            description: category.description,
            parentId: parentId ?? null,
          },
        });

    categoryIds.set(category.slug, record.id);
  }

  const authorIdsForBooks = authorIds;

  let copyCount = 0;

  for (const book of BOOKS) {
    const publisher = await db.publisher.findUnique({ where: { name: book.publisher } });
    const existing = await db.book.findUnique({ where: { isbn13: book.isbn13 } });

    const bookRecord = existing
      ? await db.book.update({
          where: { id: existing.id },
          data: {
            title: book.title,
            subtitle: book.subtitle ?? null,
            description: book.description,
            summary: book.summary,
            publicationYear: book.publicationYear,
            edition: book.edition ?? null,
            pageCount: book.pageCount ?? null,
            callNumber: book.callNumber,
            publisherId: publisher?.id ?? null,
          },
        })
      : await db.book.create({
          data: {
            isbn13: book.isbn13,
            isbn10: book.isbn10 ?? null,
            title: book.title,
            subtitle: book.subtitle ?? null,
            description: book.description,
            summary: book.summary,
            publicationYear: book.publicationYear,
            edition: book.edition ?? null,
            language: book.language ?? 'en',
            pageCount: book.pageCount ?? null,
            callNumber: book.callNumber,
            publisherId: publisher?.id ?? null,
            isReferenceOnly: book.isReferenceOnly ?? false,
          },
        });

    await db.bookAuthor.deleteMany({ where: { bookId: bookRecord.id } });
    await db.bookCategory.deleteMany({ where: { bookId: bookRecord.id } });

    await db.bookAuthor.createMany({
      data: book.authors.map((name, index) => ({
        bookId: bookRecord.id,
        authorId: authorIdsForBooks.get(name)!,
        position: index + 1,
      })),
      skipDuplicates: true,
    });

    await db.bookCategory.createMany({
      data: book.categorySlugs.map((slug, index) => ({
        bookId: bookRecord.id,
        categoryId: categoryIds.get(slug)!,
        isPrimary: index === 0,
      })),
      skipDuplicates: true,
    });

    if (book.tags?.length) {
      for (const tagName of book.tags) {
        const tag = await db.tag.upsert({
          where: { name: tagName },
          update: {},
          create: { name: tagName, label: tagName.replace(/-/g, ' ') },
        });
        await db.bookTag.upsert({
          where: { bookId_tagId: { bookId: bookRecord.id, tagId: tag.id } },
          update: {},
          create: { bookId: bookRecord.id, tagId: tag.id },
        });
      }
    }

    const allocation = COPY_ALLOCATION.find((entry) => entry.matchIsbn13 === book.isbn13);
    for (const branchAllocation of allocation?.copies ?? []) {
      const branchId = branchIds.get(branchAllocation.branchCode);
      if (!branchId) continue;

      const shelfId = branchAllocation.shelfCode
        ? shelfIds.get(`${branchAllocation.branchCode}/${branchAllocation.shelfCode}`)
        : undefined;

      const existingCopies = await db.bookCopy.count({
        where: { bookId: bookRecord.id, branchId },
      });
      for (let i = existingCopies; i < branchAllocation.count; i += 1) {
        await db.bookCopy.create({
          data: {
            bookId: bookRecord.id,
            branchId,
            shelfId: shelfId ?? null,
            accessionNumber: makeAccessionNumber(branchAllocation.branchCode, book.isbn13, i),
            barcode: makeBarcode(),
            qrToken: makeQrToken(),
            condition: 'GOOD' as CopyCondition,
            status: 'AVAILABLE',
            acquisitionDate: new Date(),
            acquisitionSource: 'PURCHASE',
          },
        });
        copyCount += 1;
      }
    }
  }

  logger.info(
    {
      authors: AUTHORS.length,
      publishers: PUBLISHERS.length,
      categories: categoryIds.size,
      books: BOOKS.length,
      copies: copyCount,
    },
    'Catalogue seeded',
  );
}

/* â”€â”€ Entry point â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€ */

async function main(): Promise<void> {
  assertNotProduction();
  logger.info({ environment: env.NODE_ENV }, 'Seeding database');

  // Reference configuration — safe to run anywhere (idempotent upserts).
  await seedPermissionsAndRoles();
  const memberTypeIds = await seedMemberTypes(prisma);
  await seedSettings(prisma);

  // Sample data — opt-in only, never implicit.
  if (wantsDemoData()) {
    const library = await seedLibrary(prisma);
    const branchIds = await seedBranches(prisma, library.id);
    const { shelves } = await seedLocations(prisma, branchIds);
    await seedUsers(prisma, branchIds, memberTypeIds);
    await seedCatalog(prisma, branchIds, shelves);

    logger.info(
      {
        accounts: SEED_USERS.length,
        note: 'Demo data. Circulation state is generated by the Phase D scenario runner.',
      },
      'Demo seed complete',
    );
    return;
  }

  logger.info(
    { note: 'Config only. Pass --demo (or SEED_DEMO_DATA=true) to also seed sample content.' },
    'Seed complete',
  );
}

main()
  .catch((error: unknown) => {
    logger.fatal({ err: error }, 'Seed failed');
    process.exitCode = 1;
  })
  .finally(() => {
    void prisma.$disconnect();
  });
